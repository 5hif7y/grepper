"""Generate src/unicode_tables.odin from regex-syntax's src/unicode_tables/*.rs.

    python tools/gen_unicode_tables.py REGEX_SYNTAX_0_8_4/src/unicode_tables

The tables are regex-syntax 0.8.4's (the version ripgrep 14.1.1 pins), as they are: each
module's ranges in one array, indexed by name; the simple case folding table; the property
name and value aliases."""
import os
import re
import sys

ESC = {"t": "\t", "n": "\n", "r": "\r", "\\": "\\", "'": "'", '"': '"', "0": "\0"}


def rust_char(lit):
    """The code point of a Rust char literal's body (between the quotes)."""
    if lit.startswith("\\u{"):
        return int(lit[3:-1], 16)
    if lit.startswith("\\x"):
        return int(lit[2:], 16)
    if lit.startswith("\\"):
        return ord(ESC[lit[1:]])
    assert len(lit) == 1, lit
    return ord(lit)


CHAR = r"'((?:\\u\{[0-9a-fA-F]+\}|\\x[0-9a-fA-F]{2}|\\.|[^'\\]))'"
STR = r'"((?:[^"\\]|\\.)*)"'


def parse_range_tables(src):
    """name -> [(lo, hi)] for every `pub const NAME: &'static [(char, char)] = &[...];`"""
    tables = {}
    for m in re.finditer(r"pub const (\w+): &'static \[\(char, char\)\] =\s*&\[(.*?)\];", src, re.S):
        pairs = re.findall(r"\(\s*" + CHAR + r"\s*,\s*" + CHAR + r"\s*\)", m.group(2))
        tables[m.group(1)] = [(rust_char(a), rust_char(b)) for a, b in pairs]
    return tables


def parse_by_name(src):
    m = re.search(r"pub const BY_NAME: [^=]*=\s*&\[(.*?)\];", src, re.S)
    if not m:
        return None
    return re.findall(r"\(\s*" + STR + r"\s*,\s*(\w+)\s*\)", m.group(1))


def main():
    d = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(os.path.dirname(here), "src", "unicode_tables.odin")
    out = []
    w = out.append
    w("// Copyright (c) 2026 Matías Alemán (5hif7y). SPDX-License-Identifier: MIT\n")
    w("// Generated by tools/gen_unicode_tables.py from regex-syntax 0.8.4's src/unicode_tables\n")
    w("// (Unicode data under its LICENSE-UNICODE). Do not edit.\n")
    w("package grepper\n\n")
    w("// a named table: its ranges in the module's array\n")
    w("Unicode_Named :: struct {\n\tname:  string,\n\tstart: i32,\n\tcount: i32,\n}\n\n")
    modules = ["age", "general_category", "grapheme_cluster_break", "perl_decimal", "perl_space",
               "perl_word", "property_bool", "script", "script_extension", "sentence_break",
               "word_break"]
    for mod in modules:
        src = open(os.path.join(d, mod + ".rs"), encoding="utf-8").read()
        tables = parse_range_tables(src)
        by_name = parse_by_name(src)
        if by_name is None:
            by_name = [(k, k) for k in tables]          # perl_word: a single table
        up = mod.upper()
        ranges = []
        index = []
        for name, const in by_name:
            t = tables[const]
            index.append((name, len(ranges), len(t)))
            ranges.extend(t)
        w("UT_%s_RANGES := [?][2]rune{\n" % up)
        for i in range(0, len(ranges), 8):
            w("\t" + " ".join("{0x%X, 0x%X}," % r for r in ranges[i:i + 8]) + "\n")
        w("}\n\n")
        w("UT_%s := [?]Unicode_Named{\n" % up)
        for name, start, count in index:
            w('\t{"%s", %d, %d},\n' % (name, start, count))
        w("}\n\n")

    # simple case folding: each code point and the code points it folds to (an orbit)
    src = open(os.path.join(d, "case_folding_simple.rs"), encoding="utf-8").read()
    body = re.search(r"CASE_FOLDING_SIMPLE[^=]*=\s*&\[(.*)\];", src, re.S).group(1)
    entries = re.findall(r"\(\s*" + CHAR + r"\s*,\s*&\[([^\]]*)\]\s*\)", body)
    flat = []
    w("// simple case folding: code point, then the start and count of its mappings in\n")
    w("// UT_CASE_FOLD_TO\n")
    w("Case_Fold_Entry :: struct {\n\tc:     rune,\n\tstart: i32,\n\tcount: i32,\n}\n\n")
    w("UT_CASE_FOLD := [?]Case_Fold_Entry{\n")
    for c, tos in entries:
        ts = [rust_char(x) for x in re.findall(CHAR, tos)]
        w("\t{0x%X, %d, %d},\n" % (rust_char(c), len(flat), len(ts)))
        flat.extend(ts)
    w("}\n\nUT_CASE_FOLD_TO := [?]rune{\n")
    for i in range(0, len(flat), 12):
        w("\t" + " ".join("0x%X," % x for x in flat[i:i + 12]) + "\n")
    w("}\n\n")

    src = open(os.path.join(d, "property_names.rs"), encoding="utf-8").read()
    pairs = re.findall(r"\(\s*" + STR + r"\s*,\s*" + STR + r"\s*\)", src)
    w("UT_PROPERTY_NAMES := [?][2]string{\n")
    for a, b in pairs:
        w('\t{"%s", "%s"},\n' % (a, b))
    w("}\n\n")

    src = open(os.path.join(d, "property_values.rs"), encoding="utf-8").read()
    body = src.split("= &[", 1)[1]
    groups = re.findall(r"\(\s*" + STR + r"\s*,\s*&\[(.*?)\]\s*,?\s*\)", body, re.S)
    w("Property_Values :: struct {\n\tproperty: string,\n\tstart:    i32,\n\tcount:    i32,\n}\n\n")
    flat = []
    w("UT_PROPERTY_VALUES := [?]Property_Values{\n")
    for prop, vals in groups:
        vs = re.findall(r"\(\s*" + STR + r"\s*,\s*" + STR + r"\s*\)", vals)
        w('\t{"%s", %d, %d},\n' % (prop, len(flat), len(vs)))
        flat.extend(vs)
    w("}\n\nUT_PROPERTY_VALUE_PAIRS := [?][2]string{\n")
    for a, b in flat:
        w('\t{"%s", "%s"},\n' % (a, b))
    w("}\n")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    print("written", dst, os.path.getsize(dst), "bytes")


if __name__ == "__main__":
    main()
