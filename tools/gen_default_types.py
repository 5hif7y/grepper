"""Generate src/default_types.odin from ripgrep's crates/ignore/src/default_types.rs.

    python tools/gen_default_types.py RIPGREP_CHECKOUT/crates/ignore/src/default_types.rs

The table is ripgrep's DEFAULT_TYPES as it is: names (an alias shares the globs) and globs."""
import os
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
body = src.split("pub(crate) const DEFAULT_TYPES", 1)[1].split("];", 1)[0]
# line comments inside the lists (no string in the table contains "//")
body = re.sub(r"//[^\n]*", "", body)
# the lists hold string literals only; a glob may contain ']' (a class), so the brackets are
# matched around whole literals
STR = r'"(?:[^"\\]|\\.)*"'
LIST = r"\[\s*((?:" + STR + r"\s*,?\s*)*)\]"
entries = re.findall(r"\(&" + LIST + r",\s*&" + LIST + r"\s*\)", body, re.S)
out = []
for names, globs in entries:
    ns = re.findall(r'"((?:[^"\\]|\\.)*)"', names)
    gs = re.findall(r'"((?:[^"\\]|\\.)*)"', globs)
    out.append((ns, gs))

here = os.path.dirname(os.path.abspath(__file__))
dst = os.path.join(os.path.dirname(here), "src", "default_types.odin")
with open(dst, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Copyright (c) 2026 Matías Alemán (5hif7y). SPDX-License-Identifier: MIT\n")
    f.write("// Generated by tools/gen_default_types.py from ripgrep 14.1.1's\n")
    f.write("// crates/ignore/src/default_types.rs. Do not edit.\n")
    f.write("package grepper\n\n")
    f.write("Default_Type :: struct {\n\tnames: []string,\n\tglobs: []string,\n}\n\n")
    f.write("DEFAULT_TYPES := [?]Default_Type{\n")
    for ns, gs in out:
        names = ", ".join('"%s"' % n for n in ns)
        globs = ", ".join('"%s"' % g for g in gs)
        f.write("\t{{%s}, {%s}},\n" % (names, globs))
    f.write("}\n")
print(len(out), "types written to", dst)
